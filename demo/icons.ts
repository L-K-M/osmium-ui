export type SpriteName = keyof typeof SPRITES;

/** A registered sprite as a CSS image, for inline styles. */
export function sprite(name: SpriteName): string {
  return `var(--osm-sprite-${name})`;
}

let registered = false;

/** Publish the demo's sprites (once per page). */
export function registerDemoSprites(): void {
  if (registered) return;
  registered = true;
  registerSprites(SPRITES, PALETTE);
}
